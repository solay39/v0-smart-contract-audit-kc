/**
 * Advanced Formal Verification Engine
 * Supports: Halmos (existing), Coq (via Coq-of-Solidity), K Framework (KEVM)
 *
 * Deploy the companion Python backend (see formal-verify-backend/)
 * and set FORMAL_VERIFY_BACKEND_URL in your env.
 */

import { NextRequest, NextResponse } from "next/server"

export const runtime = "nodejs"
export const maxDuration = 300 // proof search can be slow

// ─── Types ────────────────────────────────────────────────────────────────────

type ToolName = "halmos" | "coq" | "kframework"

interface VerificationProperty {
  id: string
  name: string
  description: string
  tool: ToolName
  spec: string // the actual proof/rule/lemma source
}

interface PropertyResult {
  property: string
  tool: ToolName
  status: "VERIFIED" | "VIOLATED" | "TIMEOUT" | "ERROR" | "UNKNOWN"
  counterexample?: string
  proof?: string
  time?: number
  error?: string
}

interface FormalVerificationReport {
  success: boolean
  contractName: string
  tools: ToolName[]
  results: PropertyResult[]
  provenSafe: string[]
  violations: string[]
  summary: {
    total: number
    verified: number
    violated: number
    errors: number
  }
}

